export const SERVICE_BY_CODE: ReadonlyMap<string, ClimateService> = new Map(SERVICES.map((s) => [s.code, s]));

const KEY = "\u0000";
const SERVICE_BY_ROW: ReadonlyMap<string, ClimateService> = new Map(SERVICES.map((s) => [`${s.category}${KEY}${s.name}`, s]));

/** The climate-sensitive service a portal row (its category and service name) stands for, or undefined. Exact text, nothing fuzzy. */
export function climateServiceFor(category: string, name: string): ClimateService | undefined {
  return SERVICE_BY_ROW.get(`${category.trim()}${KEY}${name.trim()}`);
}

