/** One way a facility_services row can match: every given part must match. `category` and `description` are the HFR's own text. */
export interface Matcher {
  category?: RegExp;
  description?: RegExp;
}

export interface ClimateService {
  /** Stable code used in exports and the database. */
  code: string;
  tier: Tier;
  category: CategoryKey;
  nameEn: string;
  nameSw: string;
  descEn: string;
  descSw: string;
  /** Why this service matters for El Niño rains and flooding. */
  rationale: string;
  source: "draft" | "added";
  /** "review" = the Kiswahili, or the mapping to the HFR service, needs a human check. */
  confidence: "high" | "review";
  /** Note on how the HFR data was matched, when it is not obvious. */
  mappingNote?: string;
  match: Matcher[];
}

