/**
 * The climate-sensitive services behind the El Niño health-facility app.
 *
 * Every entry is one real HFR service exactly as the portal files it: `category` and `name` are the portal's own text, unchanged,
 * so each climate row traces back to a row of `facility_services`. Nothing is renamed or re-grouped. The Kiswahili for the category
 * and the service sits next to it (all portal services are translated in ./translations.ts), and each entry carries a priority tier
 * (the team's five-tier ranking), a short plain-language description in both languages and a climate-health rationale.
 *
 * Source: the team's brainstorm document ("Climate-Sensitive_Services@HFs") and the dataset prompt
 * ("Climate_Sensitive_Facility_Dataset_Prompt"). Services the brainstorm names are `source: "draft"`; services the registry has that
 * the brainstorm did not name (the prompt's Step 3) are `source: "added"` so the team can review them.
 *
 * The portal sometimes files a service under the wrong category (for example immunization under "Growth Monitoring / Nutrition
 * Surveillance"); it is kept as filed and noted in `mappingNote`. `code` is a stable catalogue id (CS001, CS002, ...), not a portal
 * code: the portal gives services no codes of their own.
 * Entries marked `confidence: "review"` need a native-speaker health reviewer for the Kiswahili.
 *
 * Tiers 1 and 2 are a fixed list set by the team (Nov 2026): 7 direct services and 6 maternal services, nothing else. Earlier tier 1
 * and 2 entries (malaria tests, mental-health sub-services, nutrition, family planning and so on) were taken out; codes were not
 * renumbered, so CS001 to CS069 now have gaps. Migration 0012 cleans the database to match.
 */

