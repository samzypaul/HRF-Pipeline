import { describe, expect, it } from "vitest";
import { normalizePhone } from "../src/lib/phone";

describe("normalizePhone", () => {
  it.each([
    ["0778008577", "+255778008577"],
    ["778008577", "+255778008577"],
    ["255778008577", "+255778008577"],
    ["+255778008577", "+255778008577"],
    ["+255 778 008 577", "+255778008577"],
    ["+255(0)778008577", "+255778008577"],
    ["00255778008577", "+255778008577"],
    ["022-2123456", "+255222123456"],
    ["0713 567 896", "+255713567896"],
    ["769322239_", "+255769322239"],
    ["0712345678/0754123456", "+255712345678"],
    ["2123456/0754123456", "+255754123456"],
    ["+2550713270014", "+255713270014"],
    ["+254712345678", "+254712345678"],
  ])("%s → %s", (raw, expected) => {
    expect(normalizePhone(raw)).toBe(expected);
  });

  it.each([null, undefined, "", "N/A", "2123456", "12345", "0178008577"])("%s → null", (raw) => {
    expect(normalizePhone(raw)).toBeNull();
  });
});
